"""
Typed contracts for agent-to-agent communication.

These are pure Pydantic models — no SQLAlchemy, no LangChain, no I/O.
They form the only shared interface between Agent 1 (RAG chatbot) and
Agent 2 (admin agent), ensuring both sides evolve against the same schema.

Key types
---------
ReservationRequest   Agent 1 → bus: "I need admin approval for this booking"
AdminDecision        Admin  → bus: "Approve / Refuse, here is why"
AgentMessage         Envelope that wraps either of the above for transport
"""
from __future__ import annotations

import uuid
from datetime import datetime
from enum import Enum
from typing import Any, Optional

from pydantic import BaseModel, Field, model_validator


# ---------------------------------------------------------------------------
# Enumerations
# ---------------------------------------------------------------------------


class Decision(str, Enum):
    """Admin decision for a pending reservation."""
    APPROVE = "APPROVE"
    REFUSE  = "REFUSE"


class MessageType(str, Enum):
    """Discriminator for AgentMessage.type."""
    ESCALATION        = "ESCALATION"         # Agent 1 → Agent 2
    DECISION          = "DECISION"           # Agent 2 → Agent 1
    USER_NOTIFICATION = "USER_NOTIFICATION"  # Agent 1 → user (outcome relay)
    ERROR             = "ERROR"              # any party


# ---------------------------------------------------------------------------
# Nested helpers
# ---------------------------------------------------------------------------


class AvailabilitySnapshot(BaseModel):
    """Space availability captured at the moment of escalation (immutable snapshot)."""
    total_spaces:     int
    available_spaces: int
    is_open:          bool


# ---------------------------------------------------------------------------
# ReservationRequest  (Agent 1 → bus)
# ---------------------------------------------------------------------------


class ReservationRequest(BaseModel):
    """
    Complete, PII-safe representation of a user-confirmed reservation that is
    waiting for admin approval.

    car_plate_masked must already be masked by the caller before construction
    (e.g. "ABC****34") — this model never receives or stores the raw plate.
    """
    reservation_id:        int
    customer_name:         str
    car_plate_masked:      str                # e.g. "ABC****34"
    lot_name:              str
    start_time:            datetime
    end_time:              datetime
    price_estimate:        str                # human-readable, e.g. "~$32.00"
    availability_snapshot: AvailabilitySnapshot
    session_id:            str
    created_at:            datetime = Field(default_factory=datetime.utcnow)


# ---------------------------------------------------------------------------
# AdminDecision  (Admin → bus → Agent 1)
# ---------------------------------------------------------------------------


class AdminDecision(BaseModel):
    """
    Decision recorded by the administrator (or generated by Agent 2 on their
    behalf).

    Validation rule: *reason* is mandatory when decision is REFUSE so the
    user always receives a human-readable explanation.  For APPROVE, reason
    is an optional note (e.g. "VIP customer").
    """
    reservation_id: int
    decision:       Decision
    reason:         Optional[str] = None
    admin_id:       str
    decided_at:     datetime = Field(default_factory=datetime.utcnow)

    @model_validator(mode="after")
    def _require_reason_on_refuse(self) -> "AdminDecision":
        if self.decision == Decision.REFUSE and not (self.reason or "").strip():
            raise ValueError("reason is required when decision is REFUSE")
        return self


# ---------------------------------------------------------------------------
# AgentMessage  (envelope)
# ---------------------------------------------------------------------------


class AgentMessage(BaseModel):
    """
    Envelope that carries any agent payload over the message bus.

    message_id     — UUID4, auto-generated; unique per message instance.
    type           — discriminates the payload so receivers know how to decode it.
    payload        — serialised content (use model.model_dump(mode="json")).
    timestamp      — UTC creation time, auto-generated.
    correlation_id — equals reservation_id; ties escalations to their decisions.
    """
    message_id:     str          = Field(default_factory=lambda: str(uuid.uuid4()))
    type:           MessageType
    payload:        dict[str, Any]
    timestamp:      datetime     = Field(default_factory=datetime.utcnow)
    correlation_id: int          # = reservation_id
